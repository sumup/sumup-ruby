# frozen_string_literal: true

require "json"
require "fileutils"

module SumUpCodegen
  # A Ruby-native generator, with no network or external-reference resolution.
  # Handwritten transport and event code live outside its output directories.
  class Generator
    METHODS = %w[get post put patch delete head options].freeze
    RESERVED = %w[class module def end begin rescue ensure case when if unless else elsif while until for do next break return yield super self nil true false and or not alias defined? in then retry redo undef].freeze
    MODEL_RESERVED = %w[initialize inspect to_h to_json fields key? hash eql? object_id send public_send method methods class freeze frozen?].freeze
    HEADER = "# frozen_string_literal: true\n\n# Generated by codegen/generate.rb. DO NOT EDIT.\n\n"

    attr_reader :spec, :schemas, :operations

    def initialize(spec)
      @spec = spec
      @schemas = spec.fetch("components", {}).fetch("schemas", {}).dup
      @operations = []
      @descriptors = {}
      @enum_values = {}
      collect_operations
    end

    def generate
      # Discover inline objects before rendering so referenced types are stable.
      schemas.keys.each { |name| named_descriptor(name) }
      index = 0
      while index < schemas.length
        name, schema = schemas.to_a[index]
        if object_schema?(schema)
          properties(schema).each { |wire, field| descriptor(field, "#{name}#{constant(wire)}") }
        end
        index += 1
      end
      files = {
        "lib/sumup/types.rb" => generate_types,
        "sig/sumup/types.rbs" => generate_type_signatures,
        "lib/sumup/resources.rb" => generate_resource_index,
        "lib/sumup/event_types.rb" => generate_events,
        "sig/sumup/events.rbs" => generate_event_signatures,
        "code-samples.json" => JSON.pretty_generate(generate_samples) + "\n"
      }
      operations.group_by { |operation| operation[:tag] }.each do |tag, entries|
        files["lib/sumup/resources/#{snake(tag)}.rb"] = generate_resource(tag, entries)
        files["sig/sumup/resources/#{snake(tag)}.rbs"] = generate_resource_signatures(tag, entries)
      end
      files
    end

    def write(root, check: false)
      files = generate
      owned = %w[lib/sumup/resources/*.rb sig/sumup/resources/*.rbs].flat_map { |glob| Dir.glob(File.join(root, glob)) }
      stale = owned.reject { |path| files.key?(path.delete_prefix(root + "/")) }
      changed = files.keys.select { |path| !File.file?(File.join(root, path)) || File.binread(File.join(root, path)) != files[path].b }
      if check
        raise "Generated files are out of date: #{(changed + stale).join(", ")}" unless changed.empty? && stale.empty?
      else
        stale.each { |path| File.delete(path) }
        files.each do |path, contents|
          destination = File.join(root, path)
          FileUtils.mkdir_p(File.dirname(destination))
          File.write(destination, contents)
        end
      end
      files
    end

    def snake(value)
      name = value.to_s.gsub(/([A-Z]+)([A-Z][a-z])/, '\1_\2').gsub(/([a-z0-9])([A-Z])/, '\1_\2')
        .gsub(/[^a-zA-Z0-9_]/, "_").gsub(/_+/, "_").sub(/_+\z/, "").downcase
      name = "value_#{name}" if name.match?(/\A[0-9]/)
      RESERVED.include?(name) ? "#{name}_value" : name
    end

    def constant(value)
      result = value.to_s.gsub(/[^a-zA-Z0-9]/, "_").split("_").map { |part| part[0].upcase + part[1..] }.join
      result = "Value#{result}" if result.empty? || result.match?(/\A[0-9]/)
      result
    end

    private

    def resolve(value)
      return value unless value.is_a?(Hash) && value.key?("$ref")
      reference = value.fetch("$ref")
      raise "Only local references are supported: #{reference}" unless reference.start_with?("#/")
      target = reference.delete_prefix("#/").split("/").reduce(spec) { |node, key| node.fetch(key.gsub("~1", "/").gsub("~0", "~")) }
      target.merge(value.except("$ref"))
    end

    def merged(schema, seen = [])
      reference = schema["$ref"]
      return {} if reference && seen.include?(reference)
      seen = reference ? seen + [reference] : seen
      schema = resolve(schema)
      return schema unless schema["allOf"]
      result = schema.except("allOf")
      schema["allOf"].each do |part|
        part = merged(part, seen)
        result = part.merge(result) do |key, left, right|
          case key
          when "properties" then left.merge(right)
          when "required" then (left + right).uniq
          else right
          end
        end
      end
      result
    end

    def object_schema?(schema)
      merged(schema).key?("properties")
    end

    def properties(schema)
      merged(schema).fetch("properties", {})
    end

    def named_descriptor(name)
      return @descriptors[name] if @descriptors.key?(name)
      schema = schemas.fetch(name)
      if object_schema?(schema)
        @descriptors[name] = [:model, name]
      else
        # Mark first to break self references in aliases.
        @descriptors[name] = :any
        @descriptors[name] = descriptor(schema, name)
      end
    end

    def descriptor(schema, name)
      if schema["$ref"]
        reference = schema.fetch("$ref")
        raise "Expected a local schema reference: #{reference}" unless reference.start_with?("#/components/schemas/")
        result = named_descriptor(reference.split("/").last)
        return schema["nullable"] ? [:union, [result, :nil]] : result
      end
      if schema["allOf"]&.size == 1 && schema["allOf"].first.key?("$ref") &&
          (schema.keys - %w[allOf title description example examples deprecated readOnly writeOnly default nullable]).empty?
        return descriptor(schema["allOf"].first.merge(schema.except("allOf")), name)
      end
      canonical = schemas.find { |key, value| key != name && value == schema && object_schema?(value) }
      return named_descriptor(canonical.first) if canonical
      schema = merged(schema)
      @enum_values[name] = schema["enum"] if schema["enum"]&.all? { |value| value.is_a?(String) }
      result = if schema["oneOf"] || schema["anyOf"]
        variants = schema["oneOf"] || schema["anyOf"]
        [:union, variants.each_with_index.map { |item, index| descriptor(item, "#{name}Variant#{index + 1}") }.uniq]
      elsif schema.key?("properties")
        schemas[name] ||= schema
        @descriptors[name] ||= [:model, name]
      else
        type = schema["type"]
        type = (type - ["null"]).first if type.is_a?(Array)
        case type
        when "array" then [:array, descriptor(schema.fetch("items", {}), "#{name}Item")]
        when "object"
          additional = schema["additionalProperties"]
          [:map, additional.is_a?(Hash) ? descriptor(additional, "#{name}Value") : :any]
        when "string" then :string
        when "integer" then :integer
        when "number" then :number
        when "boolean" then :boolean
        when "null" then :nil
        else :any
        end
      end
      nullable = schema["nullable"] || (schema["type"].is_a?(Array) && schema["type"].include?("null"))
      nullable ? [:union, [result, :nil]] : result
    end

    def rbs(type)
      return {string: "String", integer: "Integer", number: "Numeric", boolean: "bool", nil: "nil", any: "untyped"}.fetch(type) if type.is_a?(Symbol)
      kind, argument = type
      case kind
      when :model then "Types::#{constant(argument)}"
      when :array then "Array[#{rbs(argument)}]"
      when :map then "Hash[String, #{rbs(argument)}]"
      when :union then "(#{argument.map { |item| rbs(item) }.uniq.join(" | ")})"
      else raise "Unknown type #{type.inspect}"
      end
    end

    def field_name(wire)
      name = snake(wire)
      MODEL_RESERVED.include?(name) ? "#{name}_value" : name
    end

    def input_rbs(type)
      return rbs(type) unless type.is_a?(Array)
      kind, argument = type
      case kind
      when :model then "#{rbs(type)} | Hash[Symbol | String, untyped]"
      when :array then "Array[#{input_rbs(argument)}]"
      when :map then "Hash[Symbol | String, #{input_rbs(argument)}]"
      when :union then "(#{argument.map { |item| input_rbs(item) }.uniq.join(" | ")})"
      else rbs(type)
      end
    end

    def comment(text, indent = "")
      text.to_s.lines.map { |line| "#{indent}##{" " + line.rstrip unless line.strip.empty?}\n" }.join
    end

    def collect_operations
      spec.fetch("paths").each do |path, original_item|
        item = resolve(original_item)
        item.each do |verb, original_operation|
          next unless METHODS.include?(verb)
          operation = resolve(original_operation)
          id = operation.fetch("operationId")
          tag = operation.fetch("tags").first
          name = snake(operation.dig("x-codegen", "method_name") || id)
          parameters = (item.fetch("parameters", []) + operation.fetch("parameters", [])).map { |parameter| resolve(parameter) }
            .to_h { |parameter| [[parameter.fetch("in"), parameter.fetch("name")], parameter] }.values
          body = resolve(operation.fetch("requestBody", {}))
          media = body.dig("content", "application/json")
          body_schema = media&.fetch("schema", {})
          if body.key?("content") && !body_schema
            raise "Unsupported request media type in #{id}"
          end
          responses = operation.fetch("responses").select { |status, _| status.start_with?("2") }
          response_by_status = responses.to_h do |status, raw_response|
            response = resolve(raw_response)
            content = response.fetch("content", {})
            content_types = content.map do |_media_type, media|
              descriptor(media.fetch("schema", {}), "#{constant(id)}Response#{status if responses.size > 1}")
            end
            type = if content_types.empty?
              :nil
            elsif content_types.size == 1
              content_types.first
            else
              [:union, content_types.uniq]
            end
            [status.to_i, type]
          end
          response_types = response_by_status.values.uniq
          response_type = (response_types.size == 1) ? response_types.first : [:union, response_types]
          @operations << {
            id: id, tag: tag, name: name, verb: verb.upcase, path: path,
            parameters: parameters, body_schema: body_schema,
            body_type: body_schema ? descriptor(body_schema, "#{constant(id)}Request") : nil,
            body_required: body.fetch("required", false), body_examples: media&.fetch("examples", {}),
            response_type: response_type, response_by_status: response_by_status,
            description: operation["description"] || operation["summary"], deprecated: operation["deprecated"]
          }
        end
      end
      duplicates = operations.group_by { |operation| [operation[:tag], operation[:name]] }.select { |_, entries| entries.size > 1 }
      raise "Duplicate resource methods: #{duplicates.keys.inspect}" unless duplicates.empty?
    end

    def generate_types
      output = HEADER + "module SumUp\n  module Types\n"
      schemas.sort.each do |name, schema|
        next unless object_schema?(schema)
        output << comment(schema["description"], "    ")
        output << "    class #{constant(name)} < Model\n"
        fields = properties(schema)
        names = fields.keys.map { |wire| field_name(wire) }
        raise "Conflicting model field names in #{name}" unless names.uniq.size == names.size
        fields.each do |wire, field|
          required = merged(schema).fetch("required", []).include?(wire)
          output << "      ##\n      # :attr_reader: #{field_name(wire)}\n"
          output << comment(field["description"], "      ")
          output << "      field :#{field_name(wire)}, #{descriptor(field, "#{name}#{constant(wire)}").inspect}, wire: #{wire.inspect}, required: #{required}\n"
        end
        output << "    end\n\n"
      end
      @enum_values.sort.each do |name, values|
        next if schemas[name] && object_schema?(schemas[name])
        output << "    # Known values; the API may return additional values.\n    module #{constant(name)}\n"
        used = []
        values.each do |value|
          key = value.upcase.gsub(/[^A-Z0-9]+/, "_").sub(/_+\z/, "")
          key = "VALUE_#{key}" unless key.match?(/\A[A-Z]/)
          raise "Duplicate enum constant #{name}::#{key}" if used.include?(key)
          used << key
          output << "      #{key} = #{value.inspect}\n"
        end
        output << "    end\n\n"
      end
      output.rstrip + "\n  end\nend\n"
    end

    def generate_type_signatures
      output = +"# Generated by codegen/generate.rb. DO NOT EDIT.\n\nmodule SumUp\n  module Types\n"
      schemas.sort.each do |name, schema|
        next unless object_schema?(schema)
        output << "    class #{constant(name)} < Model\n"
        properties(schema).each do |wire, field|
          type = rbs(descriptor(field, "#{name}#{constant(wire)}"))
          type = "(#{type})?" unless merged(schema).fetch("required", []).include?(wire)
          output << "      attr_reader #{field_name(wire)}: #{type}\n"
        end
        output << "    end\n"
      end
      @enum_values.sort.each do |name, values|
        next if schemas[name] && object_schema?(schemas[name])
        output << "    module #{constant(name)}\n"
        values.each do |value|
          key = value.upcase.gsub(/[^A-Z0-9]+/, "_").sub(/_+\z/, "")
          key = "VALUE_#{key}" unless key.match?(/\A[A-Z]/)
          output << "      #{key}: String\n"
        end
        output << "    end\n"
      end
      output + "  end\nend\n"
    end

    def parameter_name(parameter)
      field_name(parameter.fetch("name").delete_suffix("[]"))
    end

    def generate_resource(tag, entries)
      output = HEADER + "module SumUp\n  module Resources\n    class #{constant(tag)} < Resource\n"
      entries.each do |operation|
        output << comment(operation[:description], "      ")
        output << "      # @deprecated This API operation is deprecated.\n" if operation[:deprecated]
        output << "      # @return [#{rbs(operation[:response_type])}]\n"
        arguments = operation[:parameters].sort_by { |parameter| parameter["required"] ? 0 : 1 }
          .map { |parameter| "#{parameter_name(parameter)}:#{" UNSET" unless parameter["required"]}" }
        arguments << "body: UNSET" if operation[:body_schema]
        arguments << "options: nil"
        arguments << "**body_fields" if operation[:body_schema]
        [false, true].each do |with_response|
          output << "      def #{operation[:name]}#{"_with_response" if with_response}(#{arguments.join(", ")})\n"
          path = operation[:path].gsub(/\{([^}]+)\}/) do
            parameter = operation[:parameters].find { |candidate| candidate["in"] == "path" && candidate["name"] == Regexp.last_match(1) }
            raise "Missing path parameter in #{operation[:id]}" unless parameter
            "\#{path_segment(#{parameter_name(parameter)})}"
          end
          query = operation[:parameters].select { |parameter| parameter["in"] == "query" }
            .map { |parameter| "#{parameter.fetch("name").inspect} => #{parameter_name(parameter)}" }.join(", ")
          header_parameters = operation[:parameters].select { |parameter| parameter["in"] == "header" }
          unless header_parameters.empty?
            output << "        options = merge_header_options(options, {#{header_parameters.map { |parameter| "#{parameter.fetch("name").inspect} => #{parameter_name(parameter)}" }.join(", ")}})\n"
          end
          if operation[:body_schema]
            output << "        payload = request_body(body, body_fields)\n"
            if operation[:body_required]
              output << if merged(operation[:body_schema]).fetch("required", []).empty?
                "        payload = {} if payload.equal?(UNSET)\n"
              else
                "        raise ArgumentError, \"request body is required\" if payload.equal?(UNSET)\n"
              end
            end
          end
          output << "        @client.request(method: #{operation[:verb].inspect}, path: \"#{path}\",\n"
          output << "          query: {#{query}}, #{"body: payload, " if operation[:body_schema]}options: options,\n"
          output << "          response_type: #{operation[:response_by_status].inspect}, with_response: #{with_response})\n"
          output << "      end\n\n"
        end
      end
      output.rstrip + "\n    end\n  end\nend\n"
    end

    def generate_resource_index
      output = +HEADER
      tags = operations.map { |operation| operation[:tag] }.uniq.sort
      tags.each { |tag| output << "require_relative \"resources/#{snake(tag)}\"\n" }
      output << "\nmodule SumUp\n  class Client\n    RESOURCES = {\n"
      output << tags.map { |tag| "      #{snake(tag)}: Resources::#{constant(tag)}" }.join(",\n") << "\n"
      output << "    }.freeze\n\n"
      tags.each { |tag| output << "    def #{snake(tag)}\n      @resources.fetch(:#{snake(tag)})\n    end\n\n" }
      output.rstrip + "\n  end\nend\n"
    end

    def generate_resource_signatures(tag, entries)
      output = "# Generated by codegen/generate.rb. DO NOT EDIT.\n\nmodule SumUp\n  class Client\n    def #{snake(tag)}: () -> Resources::#{constant(tag)}\n  end\n  module Resources\n    class #{constant(tag)} < Resource\n"
      entries.each do |operation|
        arguments = operation[:parameters].sort_by { |parameter| parameter["required"] ? 0 : 1 }.map do |parameter|
          "#{"?" unless parameter["required"]}#{parameter_name(parameter)}: #{rbs(descriptor(parameter.fetch("schema", {}), "#{constant(operation[:id])}#{constant(parameter["name"])}"))}"
        end
        if operation[:body_schema]
          arguments << "#{"?" unless operation[:body_required]}body: #{input_rbs(operation[:body_type])}"
        end
        arguments << "?options: request_options"
        variants = [arguments]
        if operation[:body_schema] && object_schema?(operation[:body_schema])
          required = merged(operation[:body_schema]).fetch("required", [])
          body_name = (operation[:body_type].is_a?(Array) && operation[:body_type].first == :model) ? operation[:body_type].last : "#{constant(operation[:id])}Request"
          body_arguments = properties(operation[:body_schema]).map do |wire, field|
            "#{"?" unless required.include?(wire)}#{field_name(wire)}: #{input_rbs(descriptor(field, "#{body_name}#{constant(wire)}"))}"
          end
          variants << arguments.reject { |argument| argument.match?(/\A\??body:/) } + body_arguments
        end
        [false, true].each do |with_response|
          result = with_response ? "Response[#{rbs(operation[:response_type])}]" : rbs(operation[:response_type])
          output << "      def #{operation[:name]}#{"_with_response" if with_response}: "
          output << variants.map { |variant| "(#{variant.join(", ")}) -> #{result}" }.join("\n        | ") + "\n"
        end
      end
      output + "    end\n  end\nend\n"
    end

    def events
      spec.fetch("webhooks", {}).sort.map do |type, item|
        operation = resolve(item).fetch("post")
        object = operation.fetch("x-object")
        {type: type, name: constant(operation.fetch("operationId").delete_suffix("Webhook")) + "Event",
         object_type: descriptor(object, "EventResource"), resource_type: operation.fetch("x-object-type")}
      end
    end

    def generate_events
      output = HEADER + "module SumUp\n"
      events.each do |event|
        output << "  class #{event[:name]} < EventNotification\n    TYPE = #{event[:type].inspect}\n    OBJECT_TYPE = #{event[:object_type].inspect}.freeze\n    RESOURCE_TYPE = #{event[:resource_type].inspect}\n  end\n\n"
      end
      output << "  module Events\n    TYPES = {\n"
      output << events.map { |event| "      #{event[:type].inspect} => #{event[:name]}" }.join(",\n") << "\n"
      output + "    }.freeze\n  end\nend\n"
    end

    def generate_event_signatures
      output = +"# Generated by codegen/generate.rb. DO NOT EDIT.\n\nmodule SumUp\n"
      events.each do |event|
        output << "  class #{event[:name]} < EventNotification\n    TYPE: String\n    def fetch_object: (?options: request_options) -> #{rbs(event[:object_type])}\n  end\n"
      end
      output + "end\n"
    end

    def sample_value(schema, seen = [])
      return "example" if seen.size > 8
      schema = merged(schema)
      return schema["example"] if schema.key?("example")
      return schema["default"] if schema.key?("default")
      return schema["enum"].first if schema["enum"]
      return sample_value((schema["oneOf"] || schema["anyOf"]).first, seen + [true]) if schema["oneOf"] || schema["anyOf"]
      if schema["properties"]
        return schema.fetch("required", []).to_h { |key| [key, sample_value(schema["properties"].fetch(key, {}), seen + [key])] }
      end
      case schema["type"]
      when "integer", "number" then schema.fetch("minimum", 1)
      when "boolean" then true
      when "array" then [sample_value(schema.fetch("items", {}), seen + [true])]
      when "object" then {}
      else "example"
      end
    end

    def generate_samples
      samples = operations.flat_map do |operation|
        examples = operation[:body_examples] || {}
        examples = {nil => {"value" => operation[:body_schema] ? sample_value(operation[:body_schema]) : nil}} if examples.empty?
        examples.map do |example_name, raw_example|
          example = resolve(raw_example)
          arguments = operation[:parameters].select { |parameter| parameter["required"] }.map do |parameter|
            "#{parameter_name(parameter)}: #{sample_value(parameter.fetch("schema", {})).inspect}"
          end
          arguments << "body: #{ruby_literal(example.fetch("value"))}" if operation[:body_schema]
          code = "require \"sumup\"\n\nclient = SumUp::Client.new(api_key: ENV.fetch(\"SUMUP_API_KEY\"))\nresult = client.#{snake(operation[:tag])}.#{operation[:name]}(#{arguments.join(", ")})\n"
          sample = {id: [operation[:id], example_name].compact.join("."), operationId: operation[:id],
                    httpMethod: operation[:verb], path: operation[:path], sample: code}
          sample[:example] = example_name if example_name
          sample
        end
      end
      {schemaVersion: 1, language: "ruby", sdk: {module: "sumup", version: version},
       openAPIVersion: spec.fetch("info").fetch("version"), samples: samples.sort_by { |sample| sample[:id] }}
    end

    def ruby_literal(value)
      case value
      when Hash then "{#{value.map { |key, item| "#{key.inspect} => #{ruby_literal(item)}" }.join(", ")}}"
      when Array then "[#{value.map { |item| ruby_literal(item) }.join(", ")}]"
      else value.inspect
      end
    end

    def version
      @version ||= File.read(File.expand_path("../lib/sumup/version.rb", __dir__)).match(/VERSION = "([^"]+)"/)[1]
    end
  end
end
