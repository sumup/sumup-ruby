const generated = "# Generated by codegen. DO NOT EDIT.\n\n"
const header = "# frozen_string_literal: true\n\n" + generated

var methods = []string{"get", "post", "put", "patch", "delete", "head", "options"}
var reserved = strings.Fields("class module def end begin rescue ensure case when if unless else elsif while until for do next break return yield super self nil true false and or not alias defined? in then retry redo undef")
var modelReserved = strings.Fields("initialize inspect to_h to_json fields key? hash eql? object_id send public_send method methods class freeze frozen?")
var acronymRE = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
var wordRE = regexp.MustCompile(`([a-z0-9])([A-Z])`)
var nonNameRE = regexp.MustCompile(`[^a-zA-Z0-9_]+`)
var underscoresRE = regexp.MustCompile(`_+`)
var nonConstantRE = regexp.MustCompile(`[^a-zA-Z0-9]+`)
var enumRE = regexp.MustCompile(`[^A-Z0-9]+`)
var pathRE = regexp.MustCompile(`\{([^}]+)\}`)

func snake(value string) string {
	name := acronymRE.ReplaceAllString(value, "${1}_${2}")
	name = wordRE.ReplaceAllString(name, "${1}_${2}")
	name = strings.ToLower(strings.TrimRight(underscoresRE.ReplaceAllString(nonNameRE.ReplaceAllString(name, "_"), "_"), "_"))
	if len(name) > 0 && name[0] >= '0' && name[0] <= '9' {
		name = "value_" + name
	}
	if slices.Contains(reserved, name) {
		name += "_value"
	}
	return name
}
func constant(value string) string {
	parts := strings.Split(nonConstantRE.ReplaceAllString(value, "_"), "_")
	var b strings.Builder
	for _, part := range parts {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	name := b.String()
	if name == "" || (name[0] >= '0' && name[0] <= '9') {
		name = "Value" + name
	}
	return name
}
func fieldName(wire string) string {
	name := snake(wire)
	if slices.Contains(modelReserved, name) {
		name += "_value"
	}
	return name
}
func parameterName(p object) string {
	return fieldName(strings.TrimSuffix(asString(p.get("name")), "[]"))
}
func enumKey(value string) string {
	key := strings.TrimRight(enumRE.ReplaceAllString(strings.ToUpper(value), "_"), "_")
	if key == "" || key[0] < 'A' || key[0] > 'Z' {
		key = "VALUE_" + key
	}
	return key
}

// Ruby double-quoted literals must also escape interpolation sequences.
func quote(value string) string {
	q := strconv.Quote(value)
	for _, prefix := range []string{"#{", "#@", "#$"} {
		q = strings.ReplaceAll(q, prefix, "\\"+prefix)
	}
	return q
}
func comment(text, indent string) string {
	var out strings.Builder
	for line := range strings.SplitAfterSeq(text, "\n") {
		if line == "" {
			continue
		}
		line = strings.TrimRight(line, " \t\r\n")
		out.WriteString(indent + "#")
		if strings.TrimSpace(line) != "" {
			out.WriteString(" " + line)
		}
		out.WriteByte('\n')
	}
	return out.String()
}
func literal(value any) string {
	switch v := value.(type) {
	case object:
		items := []string{}
		for _, m := range v {
			items = append(items, quote(m.key)+" => "+literal(m.value))
		}
		return "{" + strings.Join(items, ", ") + "}"
	case []any:
		items := []string{}
		for _, item := range v {
			items = append(items, literal(item))
		}
		return "[" + strings.Join(items, ", ") + "]"
	case string:
		return quote(v)
	case nil:
		return "nil"
	default:
		return fmt.Sprint(v)
	}
}

type response struct {
	status int
	typ    descriptor
}
type operation struct {
	id, tag, name, verb, path, description string
	parameters                             []object
	body                                   object
	bodyType                               descriptor
	bodyRequired, deprecated               bool
	examples                               object
	responseType                           descriptor
	responses                              []response
}
type generator struct {
	spec        object
	schemas     object
	operations  []operation
	parents     map[string]string
	childNames  map[string]string
	descriptors map[string]descriptor
	enums       map[string][]string
}

func newGenerator(spec object) (*generator, error) {
	if err := validateReferences(spec, spec); err != nil {
		return nil, err
	}
	if _, ok := spec.get("paths").(object); !ok {
		return nil, fmt.Errorf("spec must contain a paths object")
	}
	g := &generator{spec: spec, schemas: slices.Clone(asObject(asObject(spec.get("components")).get("schemas"))), descriptors: map[string]descriptor{}, enums: map[string][]string{}}
	if err := g.collectTagHierarchy(); err != nil {
		return nil, err
	}
	if err := g.collect(); err != nil {
		return nil, err
	}
	return g, nil
}
func (g *generator) collect() error {
	used := map[string]bool{}
	for _, path := range asObject(g.spec.get("paths")) {
		item := g.resolve(asObject(path.value))
		for _, entry := range item {
			if !slices.Contains(methods, entry.key) {
				continue
			}
			raw := g.resolve(asObject(entry.value))
			id := asString(raw.get("operationId"))
			tags := stringsOf(raw.get("tags"))
			if id == "" || len(tags) == 0 {
				return fmt.Errorf("operation %s %s needs an operationId and tag", entry.key, path.key)
			}
			op := operation{id: id, tag: tags[0], name: snake(cmp.Or(asString(asObject(raw.get("x-codegen")).get("method_name")), id)), verb: strings.ToUpper(entry.key), path: path.key, description: cmp.Or(asString(raw.get("description")), asString(raw.get("summary"))), deprecated: truth(raw.get("deprecated"))}
			for _, param := range append(slices.Clone(asArray(item.get("parameters"))), asArray(raw.get("parameters"))...) {
				p := g.resolve(asObject(param))
				index := slices.IndexFunc(op.parameters, func(existing object) bool {
					return existing.get("in") == p.get("in") && existing.get("name") == p.get("name")
				})
				if index < 0 {
					op.parameters = append(op.parameters, p)
				} else {
					op.parameters[index] = p
				}
			}
			for _, match := range pathRE.FindAllStringSubmatch(op.path, -1) {
				if !slices.ContainsFunc(op.parameters, func(p object) bool {
					return p.get("in") == "path" && p.get("name") == match[1]
				}) {
					return fmt.Errorf("missing path parameter %s in %s", match[1], id)
				}
			}
			body := g.resolve(asObject(raw.get("requestBody")))
			media := asObject(asObject(body.get("content")).get("application/json"))
			if body.has("content") && media == nil {
				return fmt.Errorf("unsupported request media type in %s", id)
			}
			if media != nil {
				op.body = asObject(media.get("schema"))
				if op.body == nil {
					op.body = object{}
				}
				op.examples = asObject(media.get("examples"))
			}
			op.bodyRequired = truth(body.get("required"))
			successes := object{}
			for _, r := range asObject(raw.get("responses")) {
				if strings.HasPrefix(r.key, "2") {
					successes = append(successes, r)
				}
			}
			var types []descriptor
			for _, r := range successes {
				resolved := g.resolve(asObject(r.value))
				content := asObject(resolved.get("content"))
				var contentTypes []descriptor
				for _, m := range content {
					name := constant(id) + "Response"
					if len(successes) > 1 {
						name += r.key
					}
					contentTypes = append(contentTypes, g.describe(asObject(asObject(m.value).get("schema")), name))
				}
				typ := scalar("nil")
				if len(contentTypes) == 1 {
					typ = contentTypes[0]
				} else if len(contentTypes) > 1 {
					typ = descriptor{kind: "union", items: unique(contentTypes)}
				}
				status, err := strconv.Atoi(r.key)
				if err != nil {
					return fmt.Errorf("unsupported success status in %s: %s", id, r.key)
				}
				op.responses = append(op.responses, response{status, typ})
				types = append(types, typ)
			}
			types = unique(types)
			op.responseType = descriptor{kind: "union", items: types}
			if len(types) == 1 {
				op.responseType = types[0]
			}
			if op.body != nil {
				op.bodyType = g.describe(op.body, constant(id)+"Request")
			}
			key := op.tag + "/" + op.name
			if used[key] {
				return fmt.Errorf("duplicate resource method: %s", key)
			}
			used[key] = true
			g.operations = append(g.operations, op)
		}
	}
	return nil
}
func sortedMembers(o object) object {
	out := slices.Clone(o)
	slices.SortFunc(out, func(a, b member) int { return cmp.Compare(a.key, b.key) })
	return out
}
func (g *generator) generate() (map[string]string, error) {
	for _, m := range slices.Clone(g.schemas) {
		g.named(m.key)
	}
	for i := 0; i < len(g.schemas); i++ {
		m := g.schemas[i]
		if g.isObject(asObject(m.value)) {
			for _, p := range g.properties(asObject(m.value)) {
				g.describe(asObject(p.value), propertyTypeName(m.key, p.key))
			}
		}
	}
	files, err := g.renderTypeFiles()
	if err != nil {
		return nil, err
	}
	operations := make(map[string][]operation)
	for _, op := range g.operations {
		operations[op.tag] = append(operations[op.tag], op)
		for parent := g.parents[op.tag]; parent != ""; parent = g.parents[parent] {
			if _, exists := operations[parent]; exists {
				break
			}
			operations[parent] = nil
		}
	}
	tags := slices.Sorted(maps.Keys(operations))
	children := make(map[string][]string)
	for _, tag := range tags {
		if parent := g.parents[tag]; parent != "" {
			children[parent] = append(children[parent], tag)
		}
	}
	files["lib/sumup/resources.rb"] = g.renderIndex(tags)
	files["lib/sumup/event_types.rb"] = g.renderEvents()
	files["sig/sumup/events.rbs"] = g.renderEventsRBS()
	for _, tag := range tags {
		stem := g.resourceFileStem(tag)
		files["lib/sumup/resources/"+stem+".rb"] = g.renderResource(tag, operations[tag], children[tag])
		files["sig/sumup/resources/"+stem+".rbs"] = g.renderResourceRBS(tag, operations[tag], children[tag])
	}
	return files, nil
}
